/**
 * Converts the hand-drawn plates in src/woodcuts.tsx into Android
 * VectorDrawables, and emits the ink map that tints them.
 *
 *   node scripts/gen-woodcuts.mjs
 *
 * Generated rather than hand-converted for the same reason as the palette:
 * thirty-one path strings retyped by eye is thirty-one chances to corrupt one
 * silently, and a mangled plate looks like art rather than a bug.
 *
 * Every plate is a 64x64 `evenodd` path. Two also carry a stroked group, which
 * VectorDrawable expresses as extra <path> entries with strokeColor/strokeWidth
 * and no fill.
 */
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const SRC = 'src/woodcuts.tsx';
const DRAWABLE_DIR = 'android/core/designsystem/src/main/res/drawable';
const KOTLIN_OUT =
  'android/core/designsystem/src/main/kotlin/com/chroniclecryptogram/designsystem/Woodcuts.kt';

const source = readFileSync(SRC, 'utf8');

/** GiSecretBook -> woodcut_secret_book (Android resource names are snake_case). */
const resourceName = (name) =>
  'woodcut_' +
  name
    .replace(/^Gi/, '')
    .replace(/([a-z0-9])([A-Z])/g, '$1_$2')
    .toLowerCase();

/** Collapses the multi-line `d` strings the TSX indents for readability. */
const tidyPath = (d) => d.replace(/\s+/g, ' ').trim();

function parsePlates() {
  const plates = [];
  // Each plate is `function GiFoo(props) { ... }` containing one d="..." and an
  // optional stroked <g>.
  const fnRe = /function (Gi\w+)\(props: PlateProps\) \{([\s\S]*?)\n\}/g;
  let match;
  while ((match = fnRe.exec(source)) !== null) {
    const [, name, body] = match;
    const fill = body.match(/d="([\s\S]*?)"/);
    if (!fill) continue;

    const strokes = [];
    const group = body.match(
      /<g fill="none" stroke="currentColor" strokeWidth="([\d.]+)"[^>]*>([\s\S]*?)<\/g>/
    );
    if (group) {
      const width = group[1];
      const pathRe = /<path d="([^"]+)"\s*\/>/g;
      let stroke;
      while ((stroke = pathRe.exec(group[2])) !== null) {
        strokes.push({ d: tidyPath(stroke[1]), width });
      }
    }

    plates.push({ name, fill: tidyPath(fill[1]), strokes });
  }
  return plates;
}

function parseInk() {
  const block = source.match(/export const WOODCUT_INK[^{]*\{([\s\S]*?)\n\};/);
  if (!block) throw new Error('gen-woodcuts: no WOODCUT_INK block');
  const ink = {};
  const entryRe = /(Gi\w+):\s*'(\w+)'/g;
  let match;
  while ((match = entryRe.exec(block[1])) !== null) ink[match[1]] = match[2];
  return ink;
}

/**
 * `android:tint` is applied at the call site, so the drawable itself is black.
 * Path data carries no colour of its own -- the web equivalent is
 * `fill="currentColor"`.
 */
function vectorDrawable(plate) {
  const strokes = plate.strokes
    .map(
      (stroke) =>
        `    <path\n` +
        `        android:pathData="${stroke.d}"\n` +
        `        android:strokeColor="#FF000000"\n` +
        `        android:strokeWidth="${stroke.width}"\n` +
        `        android:strokeLineCap="square" />`
    )
    .join('\n');

  return (
    `<?xml version="1.0" encoding="utf-8"?>\n` +
    `<!-- Generated by scripts/gen-woodcuts.mjs from ${SRC}. Do not edit. -->\n` +
    `<vector xmlns:android="http://schemas.android.com/apk/res/android"\n` +
    `    android:width="64dp"\n` +
    `    android:height="64dp"\n` +
    `    android:viewportWidth="64"\n` +
    `    android:viewportHeight="64">\n` +
    `    <path\n` +
    `        android:pathData="${plate.fill}"\n` +
    `        android:fillColor="#FF000000"\n` +
    `        android:fillType="evenOdd" />` +
    (strokes ? `\n${strokes}` : '') +
    `\n</vector>\n`
  );
}

const plates = parsePlates();
const ink = parseInk();

if (plates.length === 0) throw new Error('gen-woodcuts: parsed no plates');

const missingInk = plates.filter((plate) => !ink[plate.name]).map((p) => p.name);
if (missingInk.length) {
  throw new Error(`gen-woodcuts: no ink for ${missingInk.join(', ')}`);
}

mkdirSync(DRAWABLE_DIR, { recursive: true });
for (const plate of plates) {
  writeFileSync(join(DRAWABLE_DIR, `${resourceName(plate.name)}.xml`), vectorDrawable(plate));
}

const inkEntries = plates
  .map(
    (plate) =>
      `    "${plate.name}" to Woodcut(R.drawable.${resourceName(plate.name)}, ` +
      `PressInk.${ink[plate.name].toUpperCase()}),`
  )
  .join('\n');

writeFileSync(
  KOTLIN_OUT,
  `package com.chroniclecryptogram.designsystem

/**
 * The press plates, generated by scripts/gen-woodcuts.mjs from
 * \`src/woodcuts.tsx\` -- do not edit.
 *
 * Keyed by the same names the web uses, so a puzzle's \`silhouette\` field
 * resolves identically on both surfaces. Each plate is drawn black and tinted at
 * the call site, which is what \`fill="currentColor"\` does on the web.
 */
data class Woodcut(val drawableRes: Int, val ink: PressInk)

enum class PressInk { LAMPBLACK, CINNABAR, PRUSSIAN, SEPIA }

val Woodcuts: Map<String, Woodcut> = mapOf(
${inkEntries}
)
`
);

const stroked = plates.filter((p) => p.strokes.length);
console.log(`Wrote ${plates.length} plates to ${DRAWABLE_DIR}`);
console.log(`  ${stroked.length} with stroked detail: ${stroked.map((p) => p.name).join(', ')}`);
console.log(`Wrote ${KOTLIN_OUT}`);
